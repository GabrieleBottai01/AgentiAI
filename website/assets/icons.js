function icon(name, size) {
  const path = ICONS[name];
  if (!path) {
    console.warn(`Icon not found: ${name}`);
    return "";
  }
  const sizeAttr = size ? ` width="${size}" height="${size}"` : "";
  return `<svg class="icon" viewBox="0 0 24 24"${sizeAttr} aria-hidden="true">${path}</svg>`;
}

function applyIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach(el => {
    if (el.dataset.iconApplied) return;
    const name = el.dataset.icon;
    el.innerHTML = icon(name) + el.innerHTML;
    el.dataset.iconApplied = "1";
  });
  // <i data-icon="name"></i>  →  replace contents with svg
  root.querySelectorAll("i[data-icon-replace]").forEach(el => {
    el.outerHTML = icon(el.dataset.iconReplace);
  });
}

document.addEventListener("DOMContentLoaded", () => applyIcons());

window.IconLib = { icon, applyIcons, ICONS };
